from __future__ import annotations

import re
from collections import defaultdict

from .model import World


RULES = r"""% Derived predicates. relation(X,Y) reads as: X is a relation of Y.
friend(X,Y) :- friendship(X,Y).
friend(X,Y) :- friendship(Y,X).
child(X,Y) :- parent(Y,X).
mother(X,Y) :- parent(X,Y), female(X).
father(X,Y) :- parent(X,Y), male(X).
sibling(X,Y) :- parent(P,X), parent(P,Y), X \= Y.
sister(X,Y) :- sibling(X,Y), female(X).
brother(X,Y) :- sibling(X,Y), male(X).
grandparent(X,Y) :- parent(X,P), parent(P,Y).
grandmother(X,Y) :- grandparent(X,Y), female(X).
grandfather(X,Y) :- grandparent(X,Y), male(X).
grandchild(X,Y) :- grandparent(Y,X).
aunt(X,Y) :- sister(X,P), parent(P,Y).
uncle(X,Y) :- brother(X,P), parent(P,Y).
cousin(X,Y) :- parent(PX,X), sibling(PX,PY), parent(PY,Y), X \= Y.
"""


def atom(value: str) -> str:
    """Quote a Python string as a safe ProbLog atom."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def world_program(world: World) -> str:
    # Sentinels keep predicates defined even in small randomly generated worlds
    # that happen to contain no person of one gender or no friendship edge.
    # They cannot participate in any relation because they are not people and
    # have no parent edges.
    lines = [
        "% Generated by prob-phantom-wiki.",
        "female('__sentinel__').",
        "male('__sentinel__').",
        "0.0::friendship('__sentinel__', '__sentinel__').",
    ]
    for person in world.people:
        lines.append(f"person({atom(person.key)}).")
        lines.append(f"{person.gender}({atom(person.key)}).")
        lines.append(f"display_name({atom(person.key)}, {atom(person.name)}).")
    lines.append("")
    choices: dict[tuple[str, str], list] = defaultdict(list)
    for fact in world.facts:
        if fact.predicate in {"job", "hobby"}:
            choices[(fact.predicate, fact.arguments[0])].append(fact)
            continue
        args = ", ".join(atom(value) for value in fact.arguments)
        lines.append(f"{fact.probability:.2f}::{fact.predicate}({args}).")
    for facts in choices.values():
        alternatives = []
        for fact in facts:
            args = ", ".join(atom(value) for value in fact.arguments)
            alternatives.append(f"{fact.probability:.6f}::{fact.predicate}({args})")
        lines.append("; ".join(alternatives) + ".")
    lines.extend(("", RULES.rstrip(), ""))
    return "\n".join(lines)


_TERM_ARGUMENT = re.compile(r"^answer\((.*)\)$")


def evaluate_answers(program: str, answer_clause: str) -> dict[str, float]:
    """Evaluate ``answer/1`` and return atom-to-marginal-probability.

    Importing ProbLog lazily keeps grammar/world generation usable for tooling
    that only wants to inspect templates.
    """
    try:
        from problog import get_evaluatable
        from problog.program import PrologString
    except ImportError as error:  # pragma: no cover - exercised by CLI error path
        raise RuntimeError("ProbLog is required for answer evaluation; install the project first") from error

    source = f"{program}\n{answer_clause}\nquery(answer(_)).\n"
    result = get_evaluatable().create_from(PrologString(source)).evaluate()
    answers: dict[str, float] = {}
    for term, probability in result.items():
        match = _TERM_ARGUMENT.match(str(term))
        if match:
            value = match.group(1)
            if len(value) >= 2 and value[0] == value[-1] == "'":
                value = value[1:-1].replace("\\'", "'").replace("\\\\", "\\")
            answers[value] = float(probability)
    return answers


def evaluate_event(
    program: str,
    clauses: list[str],
    *,
    query: str = "target_event",
    evidence: list[tuple[str, bool]] | None = None,
) -> float:
    """Evaluate a nullary event, optionally conditioned on Boolean evidence."""
    try:
        from problog import get_evaluatable
        from problog.program import PrologString
    except ImportError as error:  # pragma: no cover
        raise RuntimeError("ProbLog is required for answer evaluation; install the project first") from error

    lines = [program, *clauses]
    for event, value in evidence or []:
        lines.append(f"evidence({event}, {'true' if value else 'false'}).")
    lines.append(f"query({query}).")
    result = get_evaluatable().create_from(PrologString("\n".join(lines))).evaluate()
    for term, probability in result.items():
        if str(term) == query:
            return float(probability)
    return 0.0


def answer_records(
    probabilities: dict[str, float],
    labels: dict[str, str],
) -> list[dict[str, object]]:
    return [
        {
            "value": labels.get(value, value),
            "key": value if value in labels else None,
            "probability": round(probability, 8),
        }
        for value, probability in sorted(
            probabilities.items(), key=lambda item: (-item[1], labels.get(item[0], item[0]))
        )
    ]

